#!/usr/bin/env python3
"""tests/t_refinery.py -- refinery merge contract suite (segment assembly).

Purpose.  Assemble the six refinery lane segments into one suite per the
  merge contract: seam (the Delta-1 write-back repair plus the true-corpus
  p0-to-p6 chain vector), vacgen (the envelope casting guards and the
  two-dimensional verdict), gap (W1 gap-ledger aggregation determinism),
  render (W2 handoff row admission), calib (W4 calibration ledger
  idempotence), and sweep (the two orchestration selftests plus the
  verdict schema pins); each segment contributes its run_segment_*()
  checks and this module aggregates the per-segment tallies into one
  SUMMARY line and one TOTAL line.
Interface.  `python -I tests/t_refinery.py` runs every segment and exits
  0 when no FAIL line was produced, 1 otherwise, 2 on usage error.  Each
  segment module exposes run_segment_<name>() returning
  (passed, failed, skipped, results); importing this module spawns
  nothing (import-safe), and an absent segment file degrades to one loud
  SKIP line naming the missing path.
Dependencies.  Python 3 standard library only; the six segment modules
  under tests/refinery_segments/ load dynamically by file location; each
  segment locates the repository root on its own; zero network by
  construction (the render and sweep segments exercise only their
  offline and designed-skip faces).
Evidence.  The per-lane segment contracts (each segment prints its own
  TOTAL line when run standalone); the merge contract form of
  tests/t_engines_body.py (per-segment tally lines, SUMMARY, TOTAL).
Exit-codes.  0 all segments green (zero FAIL); 1 at least one FAIL
  (each listed, fail loud); 2 usage error.  SKIP lines name their
  missing surface and never count as passes.
"""

import importlib.util
import os
import sys

# generated bytecode stays out of the tree on every invocation form (the
# dynamic segment loads below must not leave cache artifacts behind)
sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
SEGMENTS_DIR = os.path.join(HERE, "refinery_segments")

# (segment name, file name, merge-contract entry function) in lane order
SEGMENTS = (
    ("seam", "seam.py", "run_segment_seam"),
    ("vacgen", "vacgen.py", "run_segment_vacgen"),
    ("gap", "gap.py", "run_segment_gap"),
    ("render", "render.py", "run_segment_render"),
    ("calib", "calib.py", "run_segment_calibration"),
    ("sweep", "sweep.py", "run_segment_sweep"),
)

USAGE = ("usage: python -I tests/t_refinery.py\n"
         "  runs every refinery segment; exit 0 green / 1 red / 2 usage\n")


def run_segment(name, file_name, entry):
    """Load one segment module and run its merge-contract entry; returns
    (passed, failed, skipped, results).  An absent file is one loud SKIP;
    an import or entry failure is one loud FAIL (never silent)."""
    path = os.path.join(SEGMENTS_DIR, file_name)
    if not os.path.isfile(path):
        return 0, 0, 1, [("SKIP", "segment-landed",
                          "tests/refinery_segments/%s not landed yet; the "
                          "checks of this segment activate at merge"
                          % file_name)]
    try:
        spec = importlib.util.spec_from_file_location("rqw_refinery_" + name,
                                                      path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        fn = getattr(mod, entry)
        passed, failed, skipped, results = fn()
    except Exception as exc:
        return 0, 1, 0, [("FAIL", "segment-import",
                          "tests/refinery_segments/%s raised at import, "
                          "lacks %s, or the entry raised: %r"
                          % (file_name, entry, exc))]
    return passed, failed, skipped, results


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, OSError):
            pass
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv:
        if argv[0] in ("-h", "--help"):
            print(USAGE)
            return 0
        sys.stderr.write("usage error: unknown argument %r\n" % argv[0])
        print(USAGE)
        return 2
    total_pass = total_fail = total_skip = 0
    for name, file_name, entry in SEGMENTS:
        passed, failed, skipped, results = run_segment(name, file_name, entry)
        for status, check_name, detail in results:
            print("%s %s/%s -- %s" % (status, name, check_name, detail))
        print("SEGMENT %s passed=%d failed=%d skipped=%d"
              % (name, passed, failed, skipped))
        total_pass += passed
        total_fail += failed
        total_skip += skipped
    print("SUMMARY segments=%d passed=%d failed=%d skipped=%d"
          % (len(SEGMENTS), total_pass, total_fail, total_skip))
    if total_fail:
        print("TOTAL-REFINERY RED (%d failed check(s))" % total_fail)
        return 1
    print("TOTAL-REFINERY GREEN (%d passed, %d skipped)"
          % (total_pass, total_skip))
    return 0


if __name__ == "__main__":
    sys.exit(main())
