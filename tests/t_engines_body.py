_BATTERY_CACHE = {}


def battery_patterns(wm):
    """Compile one regex per face from the map's verbatim detector branches,
    grouped by battery; English faces match case-insensitive, Chinese faces
    case-sensitive (instrument semantics)."""
    if "patterns" in _BATTERY_CACHE:
        return _BATTERY_CACHE["patterns"]
    pats = {}
    for face in wm["faces"]:
        flags = re.IGNORECASE if face.get("lang") == "en" else 0
        pats.setdefault(face["battery"], []).append(
            re.compile(face["detector_regex_branch"], flags))
    _BATTERY_CACHE["patterns"] = pats
    return pats


def battery_line_hits(text, pats):
    """Line-count semantics per battery (the instrument counts lines, not
    occurrences)."""
    hits = {}
    lines = text.splitlines()
    for battery, plist in pats.items():
        hits[battery] = sum(
            1 for line in lines if any(p.search(line) for p in plist))
    return hits


def count_em_dash(text):
    return text.count(EM_DASH)


def faces_of(wm, battery):
    return [f for f in wm["faces"] if f["battery"] == battery]


def first_face(wm, battery):
    return faces_of(wm, battery)[0]["face"]


def entry_kind(entry):
    """The three-class disposition of a suggestion entry; the contract names
    the candidate-kind vocabulary, implementations may carry it as `kind` or
    `disposition` -- both accepted, whichever is present."""
    for key in ("kind", "disposition"):
        if key in entry:
            return entry[key]
    return None


def is_guarded_entry(entry):
    """Guarded rows: the note records a context guard or a sense split
    (contract lane 2 hard rule; detected from the map's own note text)."""
    note = entry.get("note") or ""
    return ("Guarded row" in note) or ("splits the sense" in note)


