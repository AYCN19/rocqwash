def machine_regime_faces(regimes):
    """Resolve the P0 regime table entries for the three contract faces;
    returns (resolved dict face->entry, faces carrying refusal true)."""
    resolved = {}
    for face in PIPELINE_FACES:
        entry = None
        if isinstance(regimes, dict):
            entry = regimes.get(face)
        elif isinstance(regimes, (list, tuple)):
            for item in regimes:
                if isinstance(item, dict) and face in (item.get("face"),
                                                       item.get("id")):
                    entry = item
                    break
        resolved[face] = entry
    refusals = [f for f, e in resolved.items()
                if isinstance(e, dict) and e.get("refusal") is True]
    return resolved, refusals


