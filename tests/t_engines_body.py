def build_jargon_probe(jm):
    """Probe text plus the selected entries for the jargon hard-rule matrix:
    one plain replace face, one rewrite-or-delete face, one guarded replace
    face, the preserve carve-out pair, and a backticked identifier."""
    rep = next(e for e in jm["entries"]
               if e["disposition"] == "replace"
               and e.get("standard_language") == "en"
               and not e.get("exempts") and not is_guarded_entry(e))
    rod = next(e for e in jm["entries"]
               if e["disposition"] == "rewrite_or_delete")
    guard = next((e for e in jm["entries"] if is_guarded_entry(e)), None)
    carve = next((e for e in jm["entries"] if e.get("exempts")), None)
    lines = [
        "# jargon probe for the engine body contract suite",
        "# case machine replace: %s" % rep["face"],
        "# case human only: %s" % rod["face"],
    ]
    if guard:
        lines.append("# case guarded: %s" % guard["face"])
    if carve:
        lines.append("# preserve carve-out: %s stays" % carve["exempts"][0])
        lines.append("# bare form of the same face: %s" % carve["face"])
    lines.append("# identifier position stays: `%s`" % rep["face"])
    return rep, rod, guard, carve, "\n".join(lines) + "\n"


def build_segment_probe_doc():
    """Small document with prose lines around a fenced code block and a
    protected-token line, for the P1 segmentation face."""
    lines = [
        "first prose line of the probe document",
        "second prose line closes the opening passage",
        "```",
        "code = 1",
        "```",
        "third prose carries --dry-run and https://example.org/x",
        "fourth prose line closes the document",
    ]
    fence_lines = set()
    inside = False
    for idx, line in enumerate(lines, 1):
        if line.strip() == "```":
            inside = not inside
            fence_lines.add(idx)
        elif inside:
            fence_lines.add(idx)
    return "\n".join(lines) + "\n", fence_lines


