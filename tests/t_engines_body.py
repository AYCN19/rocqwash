def _stub_signatures():
    spec = importlib.util.spec_from_file_location("rqw_engbody_stub", STUB_PATH)
    stub = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(stub)
    out = {}
    for op in stub.OPERATIONS:
        out[op] = [p.name for p in inspect.signature(getattr(stub, op)).parameters.values()
                   if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)]
    return out


def run_segment_e4_pipeline():
    """tools/i18n_pipeline.py: immutable six-operation signatures, P0_REGIMES
    data, P0 refusal as a legal outcome, P1 segmentation with protection and
    ledger rows, P6 append and close validation, CLI --manifest/--stage."""
