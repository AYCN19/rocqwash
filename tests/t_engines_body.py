def base_env(extra=None, strip_gate=True):
    """Process environment for engine CLI runs; the network gate and LLM
    endpoint variables are stripped by default so every non-network path is
    proven offline and the provider faces hit their default-deny branch."""
    env = dict(os.environ)
    # child runs (the seed suite loads tools dynamically the same way) keep
    # their cache artifacts out of the tree too
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    # Force UTF-8 I/O in every child: on a Windows host the default stdout
    # codepage (charmap on the hosted image, gbk on a zh-CN host) makes a
    # child that prints Chinese prose or math symbols die with
    # UnicodeEncodeError, which the parent then reads as a red case.
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONUTF8"] = "1"
    if strip_gate:
        for key in ("ROCQWASH_MCP_ALLOW_NET", "ROCQWASH_LLM_ENDPOINT",
                    "ROCQWASH_LLM_MODEL", "ROCQWASH_LLM_KEY"):
            env.pop(key, None)
    if extra:
        env.update(extra)
    return env


def run_tool(rel_path, args, extra_env=None, strip_gate=True, cwd=None):
    """Run a tools/ CLI with the same interpreter, isolated mode, and a
    neutral environment; returns the completed process object."""
    path = rel_path if os.path.isabs(rel_path) else os.path.join(ROOT, rel_path)
    return subprocess.run(
        [sys.executable, "-I", "-X", "utf8", path] + [str(a) for a in args],
        capture_output=True, text=True, timeout=TOOL_TIMEOUT_S,
        env=base_env(extra_env, strip_gate), cwd=cwd or ROOT,
        encoding="utf-8", errors="replace")


def out_text(proc):
    return (proc.stdout or "") + (proc.stderr or "")


_ENGINE_CACHE = {}


class EngineBroken(Exception):
    """A landed engine module raised during import (fail loud, never silent)."""


def load_engine(key, results=None):
    """Load a tools/ engine module by contract key; None (with one loud SKIP
    line appended) while the file has not landed; EngineBroken surfaces as a
    FAIL through the caller."""
    if key in _ENGINE_CACHE:
        return _ENGINE_CACHE[key]
    path = os.path.join(ROOT, "tools", ENGINE_FILES[key]) if ROOT else None
    if path is None or not os.path.isfile(path):
        if results is not None:
            results.append(("SKIP", "module-landed",
                            "tools/%s not landed yet; the contract checks of "
                            "this segment activate at merge" % ENGINE_FILES[key]))
        _ENGINE_CACHE[key] = None
        return None
    spec = importlib.util.spec_from_file_location("rqw_engbody_" + key, path)
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
    except Exception as exc:
        raise EngineBroken("tools/%s loaded but raised at import: %r"
                           % (ENGINE_FILES[key], exc))
    _ENGINE_CACHE[key] = mod
    return mod


def check(results, name, thunk):
    """Run one check; assertion failures and unexpected exceptions become
    FAIL lines with the cause named; a returned string becomes the detail."""
    try:
        detail = thunk()
    except AssertionError as exc:
        results.append(("FAIL", name, str(exc) or "assertion failed"))
    except Exception as exc:
        results.append(("FAIL", name, "%s: %r" % (type(exc).__name__, exc)))
    else:
        results.append(("PASS", name, detail or "ok"))


def require_module(results, key):
    """Load an engine module for a segment; returns the module or None after
    appending the loud SKIP line that names the absent file."""
    try:
        return load_engine(key, results)
    except EngineBroken as exc:
        results.append(("FAIL", "module-import", str(exc)))
        return None


def assert_true(cond, message):
    if not cond:
        raise AssertionError(message)


