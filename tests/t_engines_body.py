        assert_true(regimes is not None, "P0_REGIMES constant missing")
        resolved, refusals = machine_regime_faces(regimes)
        lacking = [f for f, e in resolved.items() if not isinstance(e, dict)]
        assert_true(not lacking,
                    "regime table lacks contract faces: %r" % lacking)
        for face, entry in resolved.items():
            assert_true("disclosure_required" in entry and "refusal" in entry,
                        "regime %r lacks the disclosure/refusal keys" % face)
        return ("P0_REGIMES carries %s with disclosure and refusal keys; "
                "refusal-true faces: %r" % (", ".join(PIPELINE_FACES), refusals))

