def run_segment_own_register():
    """The suite eats its own cooking: battery zero on the scanned-extension
    face, em-dash zero everywhere, English-only ASCII source, five-field
    headers, no date stamps, and the fixtures proven functional."""
    results = []

    def _thunk_suite_ascii():
        data = io.open(os.path.abspath(__file__), "rb").read()
        data.decode("ascii")
        return "suite source is pure ASCII (zero CJK bytes)"

    def _thunk_battery_clean():
        pats = battery_patterns(load_json(WORD_MAP_PATH))
        scanned, total = 0, {}
        for path in lane_files():
            ext = os.path.splitext(path)[1]
            if ext not in TREE_EXTENSIONS:
                continue
            scanned += 1
            for battery, n in battery_line_hits(read_text(path), pats).items():
                total[battery] = total.get(battery, 0) + n
        assert_true(total and sum(total.values()) == 0,
                    "own-register battery hit(s) on scanned faces: %r" % total)
        return "battery zero on %d scanned file(s) across %d batteries" % (
            scanned, len(total))

    def _thunk_em_dash():
        counts = {os.path.basename(p): count_em_dash(read_text(p))
                  for p in lane_files() if os.path.isfile(p)}
        bad = {k: v for k, v in counts.items() if v}
        assert_true(not bad, "em-dash U+2014 found: %r" % bad)
        return "em-dash zero across all %d lane file(s)" % len(counts)

    def _thunk_fields():
        bad = []
        for path in (os.path.abspath(__file__), README_FIXTURE):
            text = read_text(path)
            for field in FIELDS:
                pattern = ("^[ \\t]*" if path.endswith(".py")
                           else "^[ \\t]*>?[ \\t]*")
                if not re.search(pattern + re.escape(field) + r"(?:\s|$)",
                                 text, re.M):
                    bad.append("%s lacks %s" % (os.path.basename(path), field))
        assert_true(not bad, "; ".join(bad))
        return "five-field block present in the suite module and the fixture README"

    def _thunk_no_dates():
        bad = []
        for path in lane_files():
            ext = os.path.splitext(path)[1]
            if ext not in (".py", ".md"):
                continue
            hits = DATE_STAMP_RE.findall(read_text(path))
            if hits:
                bad.append("%s carries date stamp(s) %r"
                           % (os.path.basename(path), hits[:3]))
        assert_true(not bad, "; ".join(bad))
        return "no date-stamp literal in the suite module or the README"

    def _thunk_clean_fixture():
        pats = battery_patterns(load_json(WORD_MAP_PATH))
        text = read_text(CLEAN_SAMPLE)
        hits = battery_line_hits(text, pats)
        assert_true(sum(hits.values()) == 0, "clean sample fired: %r" % hits)
        assert_true(count_em_dash(text) == 0, "clean sample carries an em-dash")
        text.encode("ascii")
        return "clean sample is battery-clean, em-dash zero, ASCII only"

    def _thunk_dirty_fixture():
        pats = battery_patterns(load_json(WORD_MAP_PATH))
        text = read_text(DIRTY_SAMPLE)
        hits = battery_line_hits(text, pats)
        fired = {b: n for b, n in hits.items() if n}
        assert_true(len(fired) >= 2 and sum(fired.values()) >= 3,
                    "dirty sample payload too weak: %r" % hits)
        assert_true(count_em_dash(text) == 0,
                    "dirty probe payload must not carry an em-dash")
        text.encode("ascii")
        return "dirty sample fires on %d batteries (%r) by design" % (
            len(fired), fired)

    def _thunk_manifests():
        required = set(MANIFEST_REQUIRED_KEYS)
        good = load_json(MANIFEST_REPO)
        missing = required - set(good)
        assert_true(not missing, "repo manifest lacks keys: %r" % sorted(missing))
        assert_true(good["target"]["face"] in PIPELINE_FACES,
                    "manifest face %r outside the contract faces"
                    % good["target"].get("face"))
        assert_true(tuple(good["linkages"]) == LINKAGE_KEYS,
                    "manifest linkages drift from the four-linkage set")
        bad = load_json(MANIFEST_BAD)
        assert_true(required - set(bad),
                    "bad-shape manifest is not actually missing required keys")
        return ("repo manifest carries the seven contract keys with face %r; "
                "bad-shape manifest lacks %r"
                % (good["target"]["face"],
                   sorted(required - set(bad))))

    for name, thunk in (
        ("suite-source-ascii", _thunk_suite_ascii),
        ("battery-clean-own-face", _thunk_battery_clean),
        ("em-dash-zero-all-files", _thunk_em_dash),
        ("five-field-headers", _thunk_fields),
        ("no-date-stamps", _thunk_no_dates),
        ("clean-sample-valid", _thunk_clean_fixture),
        ("dirty-sample-valid", _thunk_dirty_fixture),
        ("manifest-shapes-valid", _thunk_manifests),
    ):
        check(results, name, thunk)
    return _tally(results, results)


