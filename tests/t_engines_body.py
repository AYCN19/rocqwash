def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, OSError):
            pass
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv:
        if argv[0] in ("-h", "--help"):
            print(USAGE)
            return 0
        sys.stderr.write("usage error: unknown argument %r\n" % argv[0])
        print(USAGE)
        return 2
    total_pass = total_fail = total_skip = 0
    pending_modules = []
    for name, fn in SEGMENTS:
        passed, failed, skipped, results = fn()
        for status, check_name, detail in results:
            print("%s %s/%s -- %s" % (status, name, check_name, detail))
        print("SEGMENT %s passed=%d failed=%d skipped=%d"
              % (name, passed, failed, skipped))
        total_pass += passed
        total_fail += failed
        total_skip += skipped
        # pending module names for the closing notice
        for status, check_name, detail in results:
            if status == "SKIP" and "not landed yet" in detail:
                for key, file_name in sorted(ENGINE_FILES.items()):
                    if file_name in detail and key not in pending_modules:
                        pending_modules.append(key)
    print("SUMMARY segments=%d passed=%d failed=%d skipped=%d"
          % (len(SEGMENTS), total_pass, total_fail, total_skip))
    if pending_modules:
        print("PENDING modules not landed (checks activate at merge): %s"
              % ", ".join(pending_modules))
    if total_fail:
        print("TOTAL-ENGINES-BODY RED (%d failed check(s))" % total_fail)
        return 1
    print("TOTAL-ENGINES-BODY GREEN (%d passed, %d skipped)"
          % (total_pass, total_skip))
    return 0


if __name__ == "__main__":
    sys.exit(main())
