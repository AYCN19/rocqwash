def _import_names(path):
    tree = ast.parse(read_text(path))
    tops = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                tops.add(alias.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            tops.add(node.module.split(".")[0])
    return tops


def run_segment_import_face():
    """Hard gate in place of the compile face: every landed engine module
    imports standard library names only (plus the contract sibling modules);
    urllib exists only inside the two provider modules."""
    results = []
    landed, pending = [], []
    for key in sorted(ENGINE_FILES):
        path = os.path.join(ROOT, "tools", ENGINE_FILES[key]) if ROOT else None
        if path and os.path.isfile(path):
            landed.append((key, path))
        else:
            pending.append(key)
    if not landed:
        results.append(("SKIP", "modules-landed",
                        "no engine module landed yet (%d pending: %s)"
                        % (len(pending), ", ".join(sorted(pending)))))
        return _tally(results, results)
    if pending:
        results.append(("SKIP", "modules-pending",
                        "%d module(s) not landed yet, not gated: %s"
                        % (len(pending), ", ".join(sorted(pending)))))

    stdlib = frozenset(getattr(sys, "stdlib_module_names", (
        # py3.9 fallback: sys.stdlib_module_names landed in 3.10; enumerate
        # the stdlib names the seven engine bodies actually import.
        "argparse", "ast", "copy", "datetime", "hashlib", "importlib",
        "io", "json", "os", "re", "shutil", "subprocess", "sys",
        "tempfile", "time", "urllib",
    )))

    def _thunk_third_party():
        bad = []
        for key, path in landed:
            tops = _import_names(path)
            stray = sorted(
                t for t in tops
                if t not in stdlib and t not in SIBLING_MODULES
                and t != os.path.splitext(os.path.basename(path))[0])
            if stray:
                bad.append("%s imports %r" % (ENGINE_FILES[key], stray))
        assert_true(not bad, "; ".join(bad))
        return "stdlib-only import face across %d landed module(s)" % len(landed)

    def _thunk_urllib_scope():
        bad = []
        for key, path in landed:
            tops = _import_names(path)
            if "urllib" in tops and key not in URLLIB_ALLOWED_IN:
                bad.append("%s imports urllib outside the provider modules"
                           % ENGINE_FILES[key])
        assert_true(not bad, "; ".join(bad))
        return ("urllib confined to the two provider modules (%s)"
                % ", ".join(sorted(URLLIB_ALLOWED_IN)))

    for name, thunk in (
        ("stdlib-only-imports", _thunk_third_party),
        ("urllib-provider-scope", _thunk_urllib_scope),
    ):
        check(results, name, thunk)
    return _tally(results, results)


