def candidate_values(candidates):
    """Plain register values of one entry's candidate cell; the seed carries
    candidate objects {kind, value, basis} verbatim, so the value strings are
    extracted here (a bare-string candidate form is accepted too)."""
    values = []
    for cand in candidates or []:
        if isinstance(cand, dict):
            value = cand.get("value")
            if isinstance(value, str) and value:
                values.append(value)
        elif isinstance(cand, str) and cand:
            values.append(cand)
    return values


def _stub_fill(rows, skip_face_ids=()):
    """Fill handoff rows the way an external model agent would: choice is the
    first candidate, after_text mirrors it, model_id names the stub."""
    filled = []
    for row in rows:
        if row.get("face_id") in skip_face_ids:
            continue
        choice = candidate_values(row.get("candidates"))[0]             if candidate_values(row.get("candidates")) else ""
        filled.append({
            "finding_id": row["finding_id"],
            "choice": choice,
            "after_text": choice,
            "model_id": "contract-suite-stub",
        })
    return filled


